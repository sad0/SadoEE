def lua_str(s):
    s = str(s).replace('\r', '')
    n = 0
    while (']' + '=' * n + ']') in s:
        n += 1
    return '[' + '=' * n + '[' + s + ']' + '=' * n + ']'


def load():
    quests = {}
    for path in sorted(glob.glob(os.path.join(HERE, 'text', 'batch_*.json'))):
        if '.part' in path:
            continue
        for q in json.load(open(path, encoding='utf-8')):
            quests[int(q['title'])] = q
    return quests


def write(lang, quests):
    sfx = 'en' if lang == 'english' else 'fr'
    out = ['-- Quest chronicle data (%s). GENERATED by quests/build_q_lua.py from quests/text/*.json: edit those.' % lang,
           '-- Installed as override/M_PSXQD.lua; read by M_PSXQ.lua.', 'PSXQ_DATA = {']
    for strref in sorted(quests):
        q = quests[strref]
        hints = q.get('hints_' + sfx) or q.get('hints_en') or []
        sol = q.get('solution_' + sfx) or q.get('solution_en') or ''
        where = q.get('where_' + sfx) or q.get('where_en') or ''
        kind = 'main' if strref in ORDER else q.get('kind', 'side')
        out.append('[%d] = { g = %s, k = %s, o = %d, c = %s, w = %s, h = { %s }, s = %s },' % (
            strref, lua_str(q.get('game', '')), lua_str(kind), ORDER.get(strref, 0), lua_str(q.get('chapter', '')),
            lua_str(where), ', '.join(lua_str(h) for h in hints), lua_str(sol)))
    out.append('}')
    if lang == 'french':
        out.append('PSXQ_Strings = {')
        out += ['\t%s = %s,' % (k, lua_str(v)) for k, v in FR_UI.items()]
        out.append('}')
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, lang + '.lua')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('written', path, len(quests), 'quests', os.path.getsize(path), 'bytes')


def main():
    quests = load()
    for lang in ('english', 'french'):
        write(lang, quests)


if __name__ == '__main__':
    main()
